"""COLREGs 局面判定与让路责任分配。

仅实现会遇分析所需的第 13（追越）、14（对遇）、15（交叉）条，一律以
「本船」为视角给出责任。三条的适用顺序为 13 > 14 > 15：追越优先，因为
追越船在整个超越过程中始终负有让路义务，不因相对方位变化而转移。
"""
_BEAM_BACK = 22.5                # Rule 13 正横后容差
_OVERTAKE_ARC = 90.0 + _BEAM_BACK   # 112.5 目标位于本船正横后的起点
_FORWARD_ARC = 90.0 - _BEAM_BACK    # 67.5  目标位于本船正前的半锥角
_COURSE_TOL = 22.5               # IMO 会遇三分法的航向差阈值

SITUATIONS = ("追越", "对遇", "交叉", "其他")


def classify(rb, hd, own_speed_kn=0.0, target_speed_kn=0.0):
    """判定局面与责任，返回 (局面, 责任描述)。

    rb: 目标船相对本船的相对方位，0=正前方，顺时针为正，单位度
    hd: 两船航向差的绝对值，单位度，取值 [0, 180]
    own_speed_kn / target_speed_kn: 仅用于追越中段的裁决

    Rule 13 定义在**被追越船**的视角上：追越船须位于其正横后 22.5° 以外。
    换到本船视角需取反向(sic +180°)，因此：目标落在本船船首 ±67.5° 时本船
    才是追越船；目标落在本船正横后 ±67.5° 时则是目标在追越本船，本船为
    直航船。正横带的追越中段无法仅靠方位区分，改由航速高低裁决。
    """
    if hd < _COURSE_TOL:
        if rb <= _FORWARD_ARC or rb >= 360.0 - _FORWARD_ARC:
            return "追越", "目标船位于本船前方，本船为追越船，应让路"
        if _OVERTAKE_ARC <= rb <= 360.0 - _OVERTAKE_ARC:
            return "追越", "目标船正从后方超越本船，本船为直航船"
        if own_speed_kn > target_speed_kn:
            return "追越", "本船航速较高正在超越，本船应让路"
        return "追越", "目标船航速较高正在超越，本船为直航船"
    if hd > 180.0 - _COURSE_TOL:
        return "对遇", "双方均应向右转向"
    if 0.0 < rb < 180.0:
        return "交叉", "目标船位于本船右舷，本船应让路"
    if 180.0 < rb < 360.0:
        return "交叉", "目标船位于本船左舷，本船为直航船"
    return "其他", "无明确让路责任"
